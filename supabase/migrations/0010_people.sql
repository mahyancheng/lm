create table public.memories (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions (id) on delete cascade,
  character_id uuid not null references public.characters (id) on delete cascade,
  quarter integer not null,
  kind public.memory_kind not null default 'interaction',
  subject_character_id uuid references public.characters (id) on delete set null,
  subject_company_id uuid references public.companies (id) on delete set null,
  subject_player_id uuid references public.session_players (id) on delete set null,
  summary text not null,
  sentiment numeric not null default 0,
  salience numeric not null default 0.5,
  decay_rate numeric not null default 0.1,
  -- FK added in 0014_simulation.sql (sim_events).
  source_event_id uuid,
  visibility public.visibility_scope not null default 'private',
  created_at timestamptz not null default now(),
  constraint memories_quarter_positive check (quarter >= 1),
  constraint memories_summary_len check (char_length(summary) between 1 and 400),
  constraint memories_sentiment_range check (sentiment between -1 and 1),
  constraint memories_salience_range check (salience between 0 and 1),
  constraint memories_decay_range check (decay_rate between 0 and 1)
);

comment on table public.memories is
  'What a character remembers and how strongly. "Player poached two researchers" and "Player supported us in a regulatory hearing" are what a dialogue agent is given, so its behaviour is grounded in the ledger rather than invented.';

create index memories_character_idx on public.memories (character_id, quarter desc);
create index memories_subject_character_idx on public.memories (subject_character_id);
create index memories_session_quarter_idx on public.memories (session_id, quarter desc);

alter table public.memories enable row level security;

-- ---------------------------------------------------------------------------
-- connection_scores

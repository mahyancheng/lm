create table public.character_traits (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions (id) on delete cascade,
  character_id uuid not null references public.characters (id) on delete cascade,
  trait_key text not null,
  kind public.trait_kind not null default 'stable',
  value numeric not null,
  -- Stable dispositions are hidden; a few reputational traits are common knowledge.
  is_public boolean not null default false,
  updated_quarter integer,
  created_at timestamptz not null default now(),
  constraint character_traits_key_format check (trait_key ~ '^[a-z0-9_]{2,48}$'),
  constraint character_traits_value_range check (value between 0 and 100),
  constraint character_traits_unique unique (character_id, trait_key)
);

comment on table public.character_traits is
  'Stable dispositions (risk tolerance, technical orientation, financial conservatism, aggressiveness, status sensitivity) and current beliefs. Hidden by default: knowing exactly how a rival CEO is wired would remove the reason to talk to them.';

create index character_traits_character_idx on public.character_traits (character_id);
create index character_traits_session_idx on public.character_traits (session_id);

alter table public.character_traits enable row level security;


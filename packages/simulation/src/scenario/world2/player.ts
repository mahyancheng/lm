/**
 * @frontier/simulation — scenario/world2/player.ts
 *
 * The fifteen starting shapes a founder can pick in world version 2: the five
 * AI backgrounds the frozen world already had, plus two for each of the other
 * five sectors.
 *
 * A background changes *only* the shape of the player company — what it sells,
 * what it costs to run, what is on its balance sheet. Identity is fixed: the
 * company id, the founder's character id, the board, the register and the seed
 * round are the same whichever card is chosen, so every relationship, every
 * board seat and every saved reference still resolves.
 *
 * The sector and region come from the setup, not from the background: a
 * warehouse-robotics founder in South Asia pays South Asian salaries and sells
 * into South Asian demand, and the background says nothing about either.
 */


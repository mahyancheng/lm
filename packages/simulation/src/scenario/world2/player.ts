/**
 * The background a setup resolves to. A background whose sector disagrees with
 * the chosen sector is not an error: the founder picked a sector first and the
 * card second, so the sector wins and the first card in it is used.
 */
export function backgroundIdFor(setup: NewGameSetup): BackgroundId {
  const declared = setup.backgroundId;
  return sectorForBackground(declared) === setup.sector ? declared : defaultBackgroundFor(setup.sector);
}


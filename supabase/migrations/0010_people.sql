create table public.connection_scores (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions (id) on delete cascade,
  character_id uuid not null references public.characters (id) on delete cascade,
  player_id uuid references public.session_players (id) on delete set null,
  quarter integer not null,
  score numeric not null default 20,
  components jsonb not null default '{}'::jsonb,
  rank integer,
  created_at timestamptz not null default now(),
  constraint connection_scores_quarter_positive check (quarter >= 1),
  constraint connection_scores_score_range check (score between 0 and 100),
  constraint connection_scores_rank_positive check (rank is null or rank >= 1),
  constraint connection_scores_unique unique (session_id, character_id, quarter)
);

comment on table public.connection_scores is
  'Per-quarter Connection Level history. Access rule: if |Connection_A - Connection_B| <= 10 either party may initiate; otherwise only the higher-connection actor may initiate downward, unless an access override exists. Public by design — it is the rule everyone plays against.';
comment on column public.connection_scores.components is
  'Contributions to the score: founder reputation, company significance, personal wealth, board positions, investor relationships, government credibility, media influence, prior exits, public following, high-quality mutual relationships.';

create index connection_scores_session_quarter_idx
  on public.connection_scores (session_id, quarter desc);
create index connection_scores_character_idx on public.connection_scores (character_id, quarter desc);

alter table public.connection_scores enable row level security;

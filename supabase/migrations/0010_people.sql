-- ===========================================================================
-- 0010_people.sql — Frontier Capital
--
-- The people layer. Conversations emerge from actual state, not generic
-- personas: a character has stable traits, current beliefs, a directional
-- relationship with every actor they know and durable memories of what was
-- done to them.
--
-- Two separate concepts, deliberately:
--   * connection_scores — how socially/institutionally powerful someone is.
--   * relationships     — how one particular actor feels about another.
-- Access is gated by the connection GAP; feeling is gated by relationships.
-- ===========================================================================

create type public.character_archetype as enum (
  'founder',
  'chief_executive',
  'executive',
  'researcher',
  'investor',
  'director',
  'regulator',
  'politician',
  'journalist',
  'analyst',
  'employee',
  'lobbyist',
  'academic'
);

create type public.character_status as enum ('active', 'inactive', 'retired', 'deceased');

create type public.trait_kind as enum ('stable', 'belief', 'skill', 'preference');

create type public.memory_kind as enum (
  'interaction',
  'observation',
  'betrayal',
  'favour',
  'deal',
  'public_event',
  'rumour'
);

-- ---------------------------------------------------------------------------
-- characters
-- ---------------------------------------------------------------------------

create table public.characters (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions (id) on delete cascade,
  full_name text not null,
  short_name text,
  archetype public.character_archetype not null,
  title text,
  company_id uuid references public.companies (id) on delete set null,
  agency_id uuid references public.agencies (id) on delete set null,
  organisation_label text,
  bio text,
  -- true when this character is the in-world body of a session seat.
  is_player_character boolean not null default false,
  player_id uuid references public.session_players (id) on delete set null,
  -- NPC characters are always visibly labelled as AI-driven in the UI.
  is_npc boolean not null default true,
  connection_level numeric not null default 20,
  public_reputation numeric not null default 0.5,
  media_influence numeric not null default 0.1,
  personal_wealth_usd numeric not null default 0,
  status public.character_status not null default 'active',
  avatar_hint text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint characters_full_name_len check (char_length(full_name) between 1 and 120),
  constraint characters_connection_range check (connection_level between 0 and 100),
  constraint characters_reputation_range check (public_reputation between 0 and 1),
  constraint characters_media_influence_range check (media_influence between 0 and 1),
  constraint characters_wealth_nonneg check (personal_wealth_usd >= 0),
  constraint characters_player_character_consistency
    check (is_player_character = (not is_npc))
);

comment on table public.characters is
  'Every important person: founders, CEOs, investors, directors, regulators, journalists, researchers. NPC characters are LLM-driven and are always labelled as AI in the interface.';
comment on column public.characters.connection_level is
  'How socially and institutionally powerful this person is (0-100). Computed by the engine from reputation, company significance, wealth, board positions, investor relationships, government credibility, media influence and prior exits — never from follower count alone.';
comment on column public.characters.is_npc is
  'AI-driven. Every message from an is_npc character is labelled as generated by an AI character.';

create index characters_session_idx on public.characters (session_id);
create index characters_company_idx on public.characters (company_id);
create index characters_agency_idx on public.characters (agency_id);
create index characters_player_idx on public.characters (player_id);
create index characters_session_archetype_idx on public.characters (session_id, archetype);

create trigger characters_set_updated_at
  before update on public.characters
  for each row execute function public.set_updated_at();

alter table public.characters enable row level security;


-- relationships
-- ---------------------------------------------------------------------------

create table public.relationships (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions (id) on delete cascade,
  from_character_id uuid not null references public.characters (id) on delete cascade,
  to_character_id uuid not null references public.characters (id) on delete cascade,
  trust numeric not null default 50,
  respect numeric not null default 50,
  hostility numeric not null default 0,
  dependence numeric not null default 0,
  familiarity numeric not null default 0,
  -- Temporary or permanent access override: shared board, shared investor,
  -- consortium, introduction, conference, acquisition talks, legal proceeding.
  access_override text,
  access_override_until_quarter integer,
  last_interaction_quarter integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint relationships_no_self check (from_character_id <> to_character_id),
  constraint relationships_scores_range check (
    trust between 0 and 100
    and respect between 0 and 100
    and hostility between 0 and 100
    and dependence between 0 and 100
    and familiarity between 0 and 100
  ),
  constraint relationships_access_override_values check (
    access_override is null
    or access_override in (
      'shared_board', 'shared_investor', 'consortium', 'introduction',
      'conference', 'acquisition_talks', 'legal_proceeding', 'media', 'system'
    )
  ),
  constraint relationships_unique unique (session_id, from_character_id, to_character_id)
);

comment on table public.relationships is
  'Directional feelings. A respects B while B despises A is a normal, important state. Access overrides recorded here are how a low-status founder engineers a route to someone far above their connection level.';

create index relationships_from_idx on public.relationships (from_character_id);
create index relationships_to_idx on public.relationships (to_character_id);

create trigger relationships_set_updated_at
  before update on public.relationships
  for each row execute function public.set_updated_at();

alter table public.relationships enable row level security;

